namespace ACWorldEdit.Foundation.Scripting;

/// <summary>IR → readable Lua 5.1-compatible text. No timestamps, so two runs are byte-identical.</summary>
public sealed class LuaEmitter : ScriptEmitter
{
    public string Emit(IrModule module, ScriptHostProfile host)
    {
        var sections = new List<string>
        {
            Header(module, host),
            Variables(module.Variables),
            Functions(module.Functions)
        };

        if (module.Events.Count > 0)
        {
            sections.Add(string.Join("\n\n", module.Events.Select(EmitFunction)));
        }

        if (module.Registrations.Count > 0)
        {
            sections.Add(string.Join("\n", module.Registrations.Select(Registration)));
        }

        return string.Join("\n\n", sections) + "\n";
    }

    static string Header(IrModule module, ScriptHostProfile host) =>
        string.Join("\n",
        [
            "-- Generated by ACWorldEdit. Do not edit.",
            $"-- Script: {OneLine(module.Name)}",
            $"-- Host: {OneLine(host.Label)}",
            $"-- Source: {OneLine(module.SourceName)}"
        ]);

    static string Variables(IReadOnlyList<IrVariable> variables)
    {
        if (variables.Count == 0)
        {
            return "local __vars = {}";
        }

        var writer = new LuaWriter();
        writer.Line("local __vars = {");
        writer.Indent();
        for (int index = 0; index < variables.Count; index++)
        {
            var variable = variables[index];
            string value = variable.Default is null ? LuaLiteral.Nil : LuaLiteral.FromValue(variable.Default.Value);
            writer.Line($"{variable.Name} = {value}{(index == variables.Count - 1 ? "" : ",")}");
        }

        writer.Outdent();
        writer.Line("}");
        return writer.ToString().TrimEnd('\n');
    }

    static string Functions(IReadOnlyList<IrFunction> functions)
    {
        var writer = new LuaWriter();
        writer.Line("local __fns = {}");
        foreach (var function in functions)
        {
            writer.Line();
            WriteFunction(writer, $"__fns.{function.Name}", function);
        }

        return writer.ToString().TrimEnd('\n');
    }

    static string EmitFunction(IrFunction function)
    {
        var writer = new LuaWriter();
        WriteFunction(writer, function.Name, function);
        return writer.ToString().TrimEnd('\n');
    }

    static void WriteFunction(LuaWriter writer, string name, IrFunction function)
    {
        string header = function.IsEvent ? $"local function {name}" : $"function {name}";
        writer.Line($"{header}({Parameters(function)})");
        writer.Indent();
        EmitStatements(writer, function.Body);
        if (function.Returns.Count > 0 && function.Body.LastOrDefault() is not IrReturn)
        {
            writer.Line("return nil");
        }

        writer.Outdent();
        writer.Line("end");
    }

    static string Parameters(IrFunction function)
    {
        var used = UsedNames(function.Body);
        return string.Join(", ", function.Parameters.Select(parameter =>
            used.Contains(parameter.Name) ? LuaLiteral.Identifier(parameter.Name) : "_"));
    }

    static string Registration(IrRegistration registration)
    {
        var args = new List<string>(registration.ScopeValues.Select(Expression));
        args.Add(registration.EventId.ToString(System.Globalization.CultureInfo.InvariantCulture));
        args.Add(registration.FunctionName);
        if (registration.Shots > 0)
        {
            args.Add(registration.Shots.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }

        return $"{registration.Register}({string.Join(", ", args)}) -- {registration.EventName}";
    }

    static void EmitStatements(LuaWriter writer, IReadOnlyList<IrStmt> statements)
    {
        foreach (var statement in statements)
        {
            EmitStatement(writer, statement);
        }
    }

    static void EmitStatement(LuaWriter writer, IrStmt statement)
    {
        switch (statement)
        {
            case IrCallStmt call:
                writer.Line(CallText(call.Receiver, call.Call, call.Args, call.ReceiverStyle, nullable: false));
                break;
            case IrVarSet set:
                writer.Line($"{set.Name} = {Expression(set.Value)}");
                break;
            case IrLocal local:
                writer.Line($"local {local.Name} = {Expression(local.Value)}");
                break;
            case IrMultiLocal multi:
                writer.Line($"local {string.Join(", ", multi.Names)} = {Expression(multi.Value)}");
                break;
            case IrIf branch:
                writer.Line($"if {Expression(branch.Condition)} then");
                writer.Indent();
                EmitStatements(writer, branch.Then);
                writer.Outdent();
                if (branch.Else.Count > 0)
                {
                    writer.Line("else");
                    writer.Indent();
                    EmitStatements(writer, branch.Else);
                    writer.Outdent();
                }

                writer.Line("end");
                break;
            case IrReturn result:
                writer.Line(result.Values.Count == 0
                    ? "return"
                    : "return " + string.Join(", ", result.Values.Select(value => value is null ? "nil" : Expression(value))));
                break;
            case IrComment comment:
                writer.Line($"-- {OneLine(comment.Text)}");
                break;
            case IrLatent latent:
            {
                string parameters = string.Join(", ", latent.CallbackParameters.Select(parameter => parameter.Name));
                writer.Line($"local function {latent.CallbackName}({parameters})");
                writer.Indent();
                EmitStatements(writer, latent.Continuation);
                writer.Outdent();
                writer.Line("end");
                string call = Expression(latent.Call);
                writer.Line(latent.TimerIdLocal is null ? call : $"local {latent.TimerIdLocal} = {call}");
                break;
            }
            case IrWhile loop:
                writer.Line($"while {Expression(loop.Condition)} do");
                writer.Indent();
                EmitStatements(writer, loop.Body);
                writer.Outdent();
                writer.Line("end");
                break;
            case IrForRange range:
                writer.Line($"for {range.Name} = {Expression(range.From)}, {Expression(range.To)} do");
                writer.Indent();
                EmitStatements(writer, range.Body);
                writer.Outdent();
                writer.Line("end");
                break;
            case IrForEach each:
                writer.Line($"for _, {each.Name} in ipairs({Expression(each.List)}) do");
                writer.Indent();
                EmitStatements(writer, each.Body);
                writer.Outdent();
                writer.Line("end");
                break;
            default:
                throw new NotSupportedException($"Unsupported IR statement {statement.GetType().Name}.");
        }
    }

    static string Expression(IrExpr expression) => expression switch
    {
        IrLiteral literal => LuaLiteral.FromValue(literal.Value),
        IrList list => "{" + string.Join(", ", list.Items.Select(Expression)) + "}",
        IrVariableGet variable => variable.Name,
        IrCall call => CallText(call.Receiver, call.Call, call.Args, call.ReceiverStyle, call.NullableReceiver),
        IrBinary binary => $"{Operand(binary.Left)} {binary.Op} {Operand(binary.Right)}",
        IrUnary unary => $"not {Operand(unary.Operand)}",
        IrIndex index => $"{Operand(index.Target)}[{Expression(index.Key)}]",
        _ => throw new NotSupportedException($"Unsupported IR expression {expression.GetType().Name}.")
    };

    static string Operand(IrExpr expression)
    {
        string text = Expression(expression);
        return expression is IrBinary or IrUnary or IrCall { NullableReceiver: true } ? $"({text})" : text;
    }

    static string CallText(
        IrExpr? receiver, string call, IReadOnlyList<IrExpr> args, ScriptReceiverStyle style, bool nullable)
    {
        string arguments = string.Join(", ", args.Select(Expression));
        if (receiver is null || style == ScriptReceiverStyle.None || style == ScriptReceiverStyle.Global)
        {
            return $"{call}({arguments})";
        }

        string target = Expression(receiver);
        string separator = style == ScriptReceiverStyle.Dot ? "." : ":";
        string text = $"{target}{separator}{call}({arguments})";
        return nullable ? $"{target} and {text} or nil" : text;
    }

    static HashSet<string> UsedNames(IReadOnlyList<IrStmt> statements)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var statement in statements)
        {
            switch (statement)
            {
                case IrCallStmt call:
                    AddExpr(used, call.Receiver);
                    foreach (var argument in call.Args)
                    {
                        AddExpr(used, argument);
                    }
                    break;
                case IrVarSet set:
                    AddExpr(used, set.Value);
                    break;
                case IrLocal local:
                    AddExpr(used, local.Value);
                    break;
                case IrMultiLocal multi:
                    AddExpr(used, multi.Value);
                    break;
                case IrIf branch:
                    AddExpr(used, branch.Condition);
                    used.UnionWith(UsedNames(branch.Then));
                    used.UnionWith(UsedNames(branch.Else));
                    break;
                case IrReturn result:
                    foreach (var value in result.Values)
                    {
                        AddExpr(used, value);
                    }
                    break;
                case IrWhile loop:
                    AddExpr(used, loop.Condition);
                    used.UnionWith(UsedNames(loop.Body));
                    break;
                case IrForRange range:
                    AddExpr(used, range.From);
                    AddExpr(used, range.To);
                    used.UnionWith(UsedNames(range.Body));
                    break;
                case IrForEach each:
                    AddExpr(used, each.List);
                    used.UnionWith(UsedNames(each.Body));
                    break;
                case IrLatent latent:
                    AddExpr(used, latent.Call);
                    used.UnionWith(UsedNames(latent.Continuation));
                    break;
            }
        }

        return used;
    }

    static void AddExpr(HashSet<string> used, IrExpr? expression)
    {
        switch (expression)
        {
            case null:
                break;
            case IrVariableGet variable:
                used.Add(variable.Name);
                break;
            case IrCall call:
                AddExpr(used, call.Receiver);
                foreach (var argument in call.Args)
                {
                    AddExpr(used, argument);
                }
                break;
            case IrBinary binary:
                AddExpr(used, binary.Left);
                AddExpr(used, binary.Right);
                break;
            case IrUnary unary:
                AddExpr(used, unary.Operand);
                break;
            case IrIndex index:
                AddExpr(used, index.Target);
                AddExpr(used, index.Key);
                break;
        }
    }

    static string OneLine(string text) => text.Replace('\n', ' ').Replace('\r', ' ');
}
